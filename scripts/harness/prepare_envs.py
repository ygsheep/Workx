#!/usr/bin/env python3
"""把「环境预装 / 换源」烘焙进一份**独立的**数据集副本（非破坏性）。

背景见 scripts/harness/env-prep.json 与 issue #176：
Terminal-Bench 题目镜像刻意极简，依赖靠 agent 自装，吃掉大量评测预算。
本脚本对**全部 77 题**做两件事，都写进数据集**副本**：

1. **全量换源**（所有题）：把 Dockerfile 里每个 `RUN ... apt-get ...` 的
   apt 源迁到清华 http 镜像。评测机在中国大陆，直连 archive.ubuntu.com /
   deb.debian.org 拉 Release/Packages 会卡死（TCP+HEAD OK，大文件 GET 被
   干扰，实测 >600s 未完）→ 镜像构建超时。换源后 apt-get update 8.9s。
   这一步是**环境适配**，不改变题目难度。
2. **依赖预装**（仅 env-prep.json 登记的 9 题）：追加一段带标记的 RUN，
   把 solve.sh 中属于「环境搭建」的依赖提前装好，剥离环境自建噪声。

预装题会顺带删掉 task.toml 的 docker_image（force_build=false 时也强制走
我们的 Dockerfile）。保留 Dockerfile **原始 FROM**（`ubuntu:24.04` /
`python:3.13-slim-bookworm` 等，本地已缓存），因此**零 Docker Hub 依赖**。

    （曾试过把 FROM 重定向到官方预构建镜像 `alexgshaw/<task>:20251031`，
     但本机 daemon 无 HTTPS 代理、坏 mirror 移除后拉不到 Docker Hub，
     遂改为「原始 FROM + 换源」，自给自足且已验证可行。）

原始 .cache/tb2/terminal-bench 不会被改动。

用法：
    python scripts/harness/prepare_envs.py                 # 生成默认副本
    python scripts/harness/prepare_envs.py --dry-run       # 只打印将做的改动
    python scripts/harness/prepare_envs.py --tasks a b c   # 只处理指定题
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SRC = REPO_ROOT / ".cache/tb2/terminal-bench"
DEFAULT_DST = REPO_ROOT / ".cache/tb2/terminal-bench-prep"
DEFAULT_CONFIG = REPO_ROOT / "scripts/harness/env-prep.json"

MARK_BEGIN = "# --- workx env-prep begin (do not edit; generated by prepare_envs.py) ---"
MARK_END = "# --- workx env-prep end ---"

#: 构建期 apt 换国内源（2026-10-13）。
#: 评测机在中国大陆，构建期直连 archive.ubuntu.com / deb.debian.org 拉
#: Release/Packages 会卡死（TCP+HEAD 均 OK，但大文件 GET 被干扰，实测 >600s
#: 未完），直接让镜像构建超时。换清华 **http** 源后 apt-get update 8.9s、
#: 装 curl+git 10.8s。
#: ⚠️ 用 http 而非 https：构建期若经代理，https 会遇证书校验失败。
#: 覆盖 Ubuntu（deb822 的 *.sources 与老式 sources.list）与 Debian 两套源。
MIRROR_PRELUDE = (
    "sed -i "
    '-e "s|http://archive.ubuntu.com/ubuntu|http://mirrors.tuna.tsinghua.edu.cn/ubuntu|g" '
    '-e "s|http://security.ubuntu.com/ubuntu|http://mirrors.tuna.tsinghua.edu.cn/ubuntu|g" '
    '-e "s|http://ports.ubuntu.com/ubuntu-ports|http://mirrors.tuna.tsinghua.edu.cn/ubuntu-ports|g" '
    '-e "s|http://deb.debian.org/debian|http://mirrors.tuna.tsinghua.edu.cn/debian|g" '
    '-e "s|http://security.debian.org/debian-security|http://mirrors.tuna.tsinghua.edu.cn/debian-security|g" '
    "/etc/apt/sources.list /etc/apt/sources.list.d/*.sources /etc/apt/sources.list.d/*.list "
    "2>/dev/null || true; "
)

#: 幂等判定标记：line 已含该串就不再注入。
MIRROR_MARK = "mirrors.tuna.tsinghua.edu.cn"


def strip_old_block(text: str) -> str:
    pattern = re.compile(
        rf"\n?{re.escape(MARK_BEGIN)}.*?{re.escape(MARK_END)}\n?", re.S
    )
    return pattern.sub("\n", text)


def strip_docker_image(task_toml: Path, dry: bool) -> bool:
    """删掉 task.toml 的 docker_image，强制 harbor 走我们改过的 Dockerfile。"""
    text = task_toml.read_text(encoding="utf-8")
    new = re.sub(r"^[ \t]*docker_image[ \t]*=[ \t]*.*$\n?", "", text, flags=re.M)
    if new == text:
        return False
    if not dry:
        task_toml.write_text(new, encoding="utf-8", newline="\n")
    return True


def inject_mirror(text: str) -> str:
    """给所有形如 `RUN <...> apt-get ...` 的行前置换源 prelude（幂等）。

    只处理以 `RUN ` 开头、含 `apt-get`、且尚未换源的行；多行 RUN（`&& \\`
    续行）只有首行匹配，效果正确。对纯 pip 的 RUN 不动。
    """
    out = []
    for line in text.splitlines():
        if line.startswith("RUN ") and "apt-get" in line and MIRROR_MARK not in line:
            out.append("RUN " + MIRROR_PRELUDE + line[len("RUN ") :])
        else:
            out.append(line)
    return "\n".join(out)


def patch_dockerfile(dockerfile: Path, snippet: str, dry: bool) -> tuple[bool, bool]:
    """写回打补丁后的 Dockerfile，返回 (base 是否换源, 是否追加预装块)。"""
    original = dockerfile.read_text(encoding="utf-8")
    base = strip_old_block(original)
    mirrored = inject_mirror(base)
    base_mirrored = mirrored != base
    if not mirrored.endswith("\n"):
        mirrored += "\n"
    if snippet:
        new = f"{mirrored}\n{MARK_BEGIN}\n{inject_mirror(snippet.strip())}\n{MARK_END}\n"
    else:
        new = mirrored
    if new == original:
        return False, False
    if not dry:
        # ⚠️ 必须显式 newline="\n"：Windows 上 Path.write_text 默认会把 \n 转成 \r\n，
        #    而数据集必须保持 LF（卡口③；CRLF 会让 checksum 题必挂、*.sh bad interpreter）。
        dockerfile.write_text(new, encoding="utf-8", newline="\n")
    return base_mirrored, bool(snippet)



def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(DEFAULT_SRC))
    ap.add_argument("--dst", default=str(DEFAULT_DST))
    ap.add_argument("--config", default=str(DEFAULT_CONFIG))
    ap.add_argument("--tasks", nargs="*", default=None)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    src, dst = Path(args.src), Path(args.dst)
    if not src.is_dir():
        print(f"❌ 源数据集不存在：{src}")
        return 1

    cfg = json.loads(Path(args.config).read_text(encoding="utf-8"))
    prep = cfg.get("tasks", {})

    names = args.tasks or sorted(p.name for p in src.iterdir() if p.is_dir())

    if not args.dry_run:
        dst.mkdir(parents=True, exist_ok=True)

    copied, mirrored, prepended, patched_toml, failed = 0, 0, 0, 0, []
    for name in names:
        s, d = src / name, dst / name
        if not s.is_dir():
            print(f"⚠️  跳过不存在的题：{name}")
            continue
        if not args.dry_run:
            if d.exists():
                shutil.rmtree(d)
            shutil.copytree(s, d)
        copied += 1

        # 预装块：只有 env-prep.json 里登记过的题才有（其余为 ""）
        entry = prep.get(name) or {}
        snippet = (entry.get("snippet") or "").strip()

        # dry-run 下目标还没复制，存在性按源路径判断
        work = d if not args.dry_run else s
        df = work / "environment" / "Dockerfile"
        tt = work / "task.toml"
        if not df.exists():
            failed.append(f"{name}(无 Dockerfile)")
            continue

        # 全量换源（所有题）+ 可选预装块（仅登记题）
        did_mirror, did_prepend = patch_dockerfile(df, snippet, args.dry_run)
        mirrored += did_mirror
        prepended += did_prepend
        # 预装题顺带删掉 docker_image（非预装题保留，保持与官方一致）
        if snippet and strip_docker_image(tt, args.dry_run):
            patched_toml += 1

    verb = "将生成" if args.dry_run else "已生成"
    print(f"✅ {verb}数据集副本：{dst}")
    print(
        f"   任务数 {copied}｜换源 {mirrored}｜追加预装层 {prepended}｜"
        f"去除 docker_image {patched_toml}"
    )
    if prep:
        covered = [t for t in prep if (dst / t).exists() or args.dry_run]
        print(f"   预装覆盖（{len(covered)} 题）：{', '.join(sorted(covered))}")
    if failed:
        print(f"   ⚠️ 异常：{failed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

